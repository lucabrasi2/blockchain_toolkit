# Universal Transaction Model
###############################################################################


@dataclass(
    frozen=True,
    slots=True,
    kw_only=True,
)
class Transaction:
    """
    Universal blockchain transaction representation.

    This is the core transaction model used throughout UBP.

    It represents concepts common across blockchain networks.

    Blockchain-specific implementations should extend this model.

    Examples
    --------
    Ethereum adds:
        - nonce
        - gas
        - chain id
        - calldata

    Bitcoin adds:
        - inputs
        - outputs
        - satoshi fees
    """


    tx_hash: str


    network: str


    sender: TransactionParticipant


    receiver: TransactionParticipant


    asset: str


    amount: Decimal


    status: TransactionStatus


    transaction_type: TransactionType


    timestamp: Optional[int] = None


    fee: Optional[TransactionFee] = None


    confirmation: Optional[
        TransactionConfirmation
    ] = None


    metadata: Optional[
        TransactionMetadata
    ] = None



@dataclass(
    frozen=True,
    slots=True,
    kw_only=True,
)
class EthereumTransaction(Transaction):
    """
    Ethereum-specific transaction model.

    Extends the universal transaction model with EVM execution details
    such as nonce, gas parameters, calldata, and receipt information.
    """


    nonce: int


    chain_id: int


    gas: EthereumGasInfo


    input_data: str


    function_selector: Optional[str] = None


    contract_address: Optional[str] = None


    receipt: Optional[EthereumTransactionReceipt] = None



