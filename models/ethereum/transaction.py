###############################################################################
# Ethereum Transaction Receipt
###############################################################################


@dataclass(
    frozen=True,
    slots=True,
)
class EthereumTransactionReceipt:
    """
    Ethereum transaction execution result.

    Represents the information returned by an Ethereum node after
    a transaction has been mined.

    Contains:
    - execution status
    - block information
    - gas consumption
    - contract creation details
    - emitted logs
    """


    block_number: Optional[int]


    block_hash: Optional[str]


    transaction_index: Optional[int]


    status: Optional[int]


    gas_used: Optional[int]


    cumulative_gas_used: Optional[int]


    contract_address: Optional[str]


    logs: tuple[EthereumTransactionLog, ...]



###############################################################################
# Ethereum Gas Information
###############################################################################


@dataclass(
    frozen=True,
    slots=True,
)
class EthereumGasInfo:
    """
    Ethereum gas execution information.

    This model stores EVM transaction fee details.

    Examples
    --------

    Legacy Ethereum transaction:

        gas_price

    EIP-1559 transaction:

        max_fee_per_gas
        max_priority_fee_per_gas
        effective_gas_price
    """


    gas_limit: int


    gas_used: Optional[int]


    gas_price: Optional[int]


    max_fee_per_gas: Optional[int]


    max_priority_fee_per_gas: Optional[int]


    effective_gas_price: Optional[int]



