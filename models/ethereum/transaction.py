# Ethereum Serialization Helpers
###############################################################################


def ethereum_transaction_to_dict(
    transaction: EthereumTransaction,
) -> Dict[str, Any]:
    """
    Convert Ethereum transaction model into
    serializable dictionary format.

    Useful for:

    - API responses
    - JSON output
    - Database storage
    - Transaction reports
    """


    return {

        "tx_hash":
            transaction.tx_hash,


        "network":
            transaction.network,


        "sender":
            transaction.sender.address,


        "receiver":
            transaction.receiver.address,


        "asset":
            transaction.asset,


        "amount":
            str(transaction.amount),


        "status":
            transaction.status.value,


        "transaction_type":
            transaction.transaction_type.value,


        "nonce":
            transaction.nonce,


        "chain_id":
            transaction.chain_id,


        "gas": {

            "limit":
                transaction.gas.gas_limit,

            "used":
                transaction.gas.gas_used,

            "gas_price":
                transaction.gas.gas_price,

            "max_fee_per_gas":
                transaction.gas.max_fee_per_gas,

            "max_priority_fee_per_gas":
                transaction.gas.max_priority_fee_per_gas,

            "effective_gas_price":
                transaction.gas.effective_gas_price,

        },


        "input_data":
            transaction.input_data,


        "function_selector":
            transaction.function_selector,


        "contract_address":
            transaction.contract_address,


        "receipt": (

            {

                "block_number":
                    transaction.receipt.block_number,

                "block_hash":
                    transaction.receipt.block_hash,

                "status":
                    transaction.receipt.status,

                "gas_used":
                    transaction.receipt.gas_used,

                "contract_address":
                    transaction.receipt.contract_address,

                "logs_count":
                    len(
                        transaction.receipt.logs
                    ),

            }

            if transaction.receipt

            else None

        ),

    }



