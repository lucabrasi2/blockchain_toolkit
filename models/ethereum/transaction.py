@dataclass(
    frozen=True,
    slots=True,
)
class EthereumTransactionLog:
    """
    Represents an Ethereum event log entry.

    Ethereum logs are generated by smart contracts through
    LOG opcodes and are commonly used for:

    - ERC-20 transfers
    - NFT events
    - Contract state changes
    """


    address: str


    topics: tuple[str, ...]


    data: str



