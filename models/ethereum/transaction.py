def create_ethereum_transaction(
    *,
    tx_hash: str,
    network: str,
    sender: TransactionParticipant,
    receiver: TransactionParticipant,
    amount: Decimal,
    status: TransactionStatus,
    transaction_type: TransactionType,
    nonce: int,
    chain_id: int,
    gas: EthereumGasInfo,
    asset: str = "ETH",
    input_data: str = "0x",
    function_selector: Optional[str] = None,
    contract_address: Optional[str] = None,
    fee: Optional[TransactionFee] = None,
    metadata: Optional[TransactionMetadata] = None,
    receipt: Optional[EthereumTransactionReceipt] = None,
) -> EthereumTransaction:
    """
    Create an Ethereum transaction model.
    """


    return EthereumTransaction(

        tx_hash=tx_hash,

        network=network,

        sender=sender,

        receiver=receiver,

        asset=asset,

        amount=amount,

        status=status,

        transaction_type=transaction_type,

        nonce=nonce,

        chain_id=chain_id,

        gas=gas,

        input_data=input_data,

        function_selector=function_selector,

        contract_address=contract_address,

        fee=fee,

        metadata=metadata,

        receipt=receipt,

    )


